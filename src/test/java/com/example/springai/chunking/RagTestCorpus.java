    /** 构造一个带 factId / source / corpus 标记的 chunk（id 交给向量库生成 UUID） */
    private static Document doc(String factId, String source, String content) {
        return new Document(content, Map.of(
                "factId", factId,
                "source", source,
                "corpus", CORPUS));
    }

    /** 清空旧数据并灌入语料，返回灌入条数 */
    public static int seed(VectorStore store, JdbcTemplate jdbc) {
        jdbc.update("DELETE FROM vector_store");
        List<Document> docs = documents();
        store.add(docs);
        return docs.size();
    }

    /** 判断语料是否已灌库（幂等，避免每次跑测试都重复灌） */
    public static boolean isSeeded(JdbcTemplate jdbc) {
        Integer n = jdbc.queryForObject(
                "SELECT COUNT(*) FROM vector_store WHERE metadata->>'corpus' = ?",
                Integer.class, CORPUS);
        return n != null && n == documents().size();
    }

    /** 从 Document 提取事实标识（ground-truth 用 metadata.factId） */
    public static String factId(Document d) {
        return String.valueOf(d.getMetadata().getOrDefault("factId", ""));
    }
